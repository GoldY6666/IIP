// 表格区的布局常量。
//
// **文件名带 list 前缀是刻意的**（2026-10-04 踩过）：
// 本目录已有 `Layout.tsx`（应用外壳），而本文件最初叫 `layout.ts` ——
// **Windows 大小写不敏感**，两个文件被解析成同一个，
// 表现为 `App.tsx: Module 'components/Layout' has no default export`
// 加一串 `differs only in casing`，vite build 直接崩。
// 即便在 Linux 上能跑，跨平台构建也会不一致。
// 故凡与既有文件**仅大小写不同**的名字都要避开。
//
// 为什么抽出来而不是每个页面各写一个数字：
// 三张列表页（事件 / 待确认 / 告警）需要**同一个** minHeight ——
// 不一致会让用户在页面之间切换时感到「表格区高度在跳」，
// 而这种跳动没有任何功能含义，纯粹是实现细节泄漏到观感里。
//
// 未来若要按视口动态计算（如 `calc(100vh - 260px)`），
// 改这一处即可，三页自动同步。

/**
 * LIST_MIN_HEIGHT 是表格区的最小高度（px）。
 *
 * 解决的问题（实测截图暴露）：antd Table 按**实际行数**收缩，
 * 只有 3 行数据时表格就只占 3 行高，于是页面下半部约 60% 是空白。
 * 在 1600px 宽屏上那片空白看起来像「页面没加载完」，
 * 用户会反复刷新等它出来。
 *
 * **520 是实测调出来的**：截图视口 1000px 高，减去 Header 52 +
 * Content padding 40 + 页脚条 40 ≈ 870 可用；420 只填一半，
 * 底部仍空一大片；再高则表格**内部**会出现「行悬浮高亮区也是空的」
 * 那��更怪的状态。
 *
 * 不用 `calc(100vh - X)` 的理由：视口高度随窗口变化，
 * 小窗口下按比例算出的值可能反而比内容还矮，minHeight 失去意义；
 * 而固定值在小窗口下只是"框矮一点"，不会出错。
 *
 * 刻意**不给固定 height**：只有 3 行时表格内部会出现一大片空白
 * （行悬浮区也是空的），比现在更怪。minHeight 只保证
 * 「页面有个完整框架」，行多时自然向下生长。
 */
export const LIST_MIN_HEIGHT = 520