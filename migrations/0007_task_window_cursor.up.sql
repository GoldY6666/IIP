-- IIP M4 · 0007_task_window_cursor.up.sql
-- 规格来源：docs/IIP-M4详细开发手册.md §4.2（修订：窗口游标）与 §4.1
--
-- 本迁移为「同一事件被重复采集」的问题加一个游标列，改动面 = **1 列**，
-- 不新增/删除表，不改任何既有约束，不改 0001–0006。
--
-- 背景
-- ----
-- 新告警合入已有事件会触发新一轮采集。若每轮都从事故起点重采，
-- 同一批 RED 指标会以完全相同的 (source, query, timestamp) 再落库一份，
-- 页面上出现两份一模一样的证据，且证据表按无效数据膨胀。
--
-- 处置：任务行记住「这个事件已采到哪个时刻」，下一轮的窗口起点取该值，
-- 每轮只采新增区间（手册 §4.2 的修订段）。
--
-- 为什么落在 tasks 表而不是别的三个地方
-- ----------------------------------
--   * 放进 payload（jsonb）？payload 是**入队输入**，而游标是**执行结果**。
--     worker 改写调用方写的输入是不洁的，且 payload 的 NOT EXISTS 判定
--     （EnqueueTaskIfAbsent）会连带受影响。
--   * 从 evidence 表取 max(timestamp)？那是「证据自身时刻」，
--     与「窗口终点」不是一回事；且**采到 0 条证据时游标不推进**，
--     同一个空窗口会被下一轮重新采一遍，永远推进不了。
--   * 单独一张进度表？为一个标量建表，且要多维护一份一致性。
--
-- 为什么可空
-- ----------
-- 存量行（若从 0005 直接升上来）没有窗口概念，NULL 即「尚未采集过」。
-- 首次采集的窗口起点由事件开始时间推导，不需要游标。
--
-- down 的破坏性：**是** —— 全部游标丢失，回滚后下一轮采集会退回
-- 「从事故起点重采」，即本迁移要解决的那个问题。tasks 表的数据本身不丢。
-- ============================================================================

ALTER TABLE tasks
    ADD COLUMN IF NOT EXISTS window_end TIMESTAMPTZ;

COMMENT ON COLUMN tasks.window_end IS
    '本任务实际采集到的窗口终点；NULL 表示尚未采集过。'
    '下一轮采集的窗口起点取该值，只采新增区间（手册 §4.2）。'
    '注意：采到 0 条证据时也要写入 —— 否则空窗口会被反复重采，游标永不推进。';

-- ----------------------------------------------------------------------------
-- 索引：idx_tasks_window_cursor (kind, window_end DESC)
--
-- 查询「某事件已采到哪儿」走的是 payload->>'incident_id'，本索引服务的是
-- 「按 kind 取最近游标」这一形态。任务表是 M4 里唯一单调增长的表
-- （done/dead 行不删），但它的增长被 attempts<=3 的死信机制限死，
-- 增长量级比 evidence 表小两三个数量级 —— 因此**不建索引**：
-- 全表扫描在这个量级下是毫秒级，而索引会在每次任务完成时多一次写放大。
--
-- 若将来任务量级上到十万行以上（多事件 × 高频合入），再补这个索引；
-- 那时应该改成 (kind, (payload->>'incident_id'), window_end DESC) 的复合索引，
-- 因为实际查询一定带 incident_id 条件。
-- ----------------------------------------------------------------------------
