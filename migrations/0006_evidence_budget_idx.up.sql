-- 规格来源：docs/IIP-M4详细开发手册.md §4.2（T4.6 采集预算）/ §五
--
-- 本迁移只加**一个索引**，不改任何表结构、不改任何列、不动既有 CHECK 约束。
--
-- 为什么需要它：0005 已建 idx_evidence_incident_type(incident_id, type)，
-- 它服务的是「某事件的某一类证据」这个组合过滤。但 T4.6 的实际读法是
-- **取该事件最新的 N 条并给出真计数**：
--
--   SELECT ... WHERE incident_id = $1 [AND type = $2]
--    ORDER BY created_at DESC, id DESC LIMIT 51
--
-- 这个查询用不上0005 的索引做排序 —— 单/双列索引不含created_at，
-- PG 只能对命中的行**额外排序**。证据表是 M4 里唯一会随时间单调增长的表
-- （每事件最多 50 条 × 事件数），排序列缺失的代价会随数据量线性上升。
--
-- 复合索引的列顺序有讲究：
--   * incident_id 在前 —— 它是等值条件，命中后即可定位到该事件的全部证据；
--   * created_at DESC 在后 —— 排序键跟在等值列后面，索引才能直接按序输出，
--     不需要额外的 Sort 节点；
--   * id DESC 收尾 —— created_at 相同（同一批采集同秒落库）时提供确定性的
--     次序。**没有它，同秒证据的返回顺序会随执行计划变化**，
--     页面上的证据列表会在两次刷新间跳动。
--
-- 刻意不覆盖 type：加上它会让索引变宽三成，而 type 只是**可选**过滤条件
-- （不传时是主路径）。等type 成为瓶颈时再加部分索引也不迟。
--
-- 不改 0001–0005（AGENTS.md 约束 10 冻结），本文件为唯一新增。
-- 幂等：CREATE INDEX IF NOT EXISTS，重复执行不会叠加。
-- ============================================================================

CREATE INDEX IF NOT EXISTS idx_evidence_incident_created
    ON evidence(incident_id, created_at DESC, id DESC);
